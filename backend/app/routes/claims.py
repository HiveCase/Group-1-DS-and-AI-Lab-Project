@router.get('/{claim_id}/annotated-photo')
def get_annotated_photo(claim_id: str, db: Session = Depends(get_db)):
    """Returns the claim's primary uploaded photo with the damage-detection
    model's bounding boxes drawn on it, so an adjuster can see what the
    model predicted without leaving the dashboard. Falls back to the raw
    photo if detections aren't available yet (analysis still pending)."""
    claim = ClaimService(db).get_claim(claim_id)
    photos = claim.photos or []
    if not photos:
        raise HTTPException(status_code=404, detail='No photo uploaded for this claim')
    photo = photos[0]
    source_path = Path(photo.file_path)
    if not source_path.exists():
        raise HTTPException(status_code=404, detail='Photo file is missing on disk')

    if photo.annotated_path and Path(photo.annotated_path).exists():
        return FileResponse(photo.annotated_path, media_type='image/jpeg')

    detections = claim.analysis_result.detections if claim.analysis_result else None
    if detections:
        annotated_path = _orchestrator.damage_service.annotate_image(source_path, detections)
        if annotated_path and Path(annotated_path).exists():
            photo.annotated_path = annotated_path
            db.add(photo)
            db.commit()
            return FileResponse(annotated_path, media_type='image/jpeg')
    return FileResponse(source_path, media_type=photo.mime_type or 'image/jpeg')

@router.get('/{claim_id}/detail')
def get_claim_detail(claim_id: str, db: Session = Depends(get_db)):
    claim = ClaimService(db).get_claim(claim_id)
    if claim.analysis_result is None:
        return {
            'claim_id': claim.claim_id,
            'status': claim.status,
            'analysis_result': {'status': 'pending'},
        }
    return {
        'claim_id': claim.claim_id,
        'status': claim.status,
        'analysis_result': {
            'status': claim.analysis_result.status,
            'severity_label': claim.analysis_result.severity_label,
            'severity_score': str(claim.analysis_result.severity_score) if claim.analysis_result.severity_score is not None else None,
            'detections': claim.analysis_result.detections,
            'policy_findings': claim.analysis_result.policy_findings,
            'recommendation': claim.analysis_result.recommendation,
            'confidence_score': str(claim.analysis_result.confidence_score) if claim.analysis_result.confidence_score is not None else None,
            'explanation': claim.analysis_result.explanation,
            'fraud_score': str(claim.analysis_result.fraud_score) if claim.analysis_result.fraud_score is not None else None,
            'report_json': claim.analysis_result.report_json,
            'needs_human_review': claim.analysis_result.needs_human_review,
        },
    }

DECISION_TO_STATUS = {
    'approved': 'approved',
    'denied': 'denied',
    'request_more_info': 'under review',
}


@router.post('/{claim_id}/decision', response_model=DecisionRead)
def submit_decision(claim_id: str, payload: DecisionRequest, db: Session = Depends(get_db)):
    claim = ClaimService(db).get_claim(claim_id)
    record = claim.decision_record or DecisionRecord(claim=claim)
    record.decision = payload.decision
    record.reasoning_note = payload.reasoning_note
    record.settlement_amount = payload.settlement_amount
    db.add(record)
    claim.status = DECISION_TO_STATUS.get(payload.decision, claim.status)
    db.commit()
    db.refresh(record)
    return record

